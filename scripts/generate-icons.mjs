import fs from "node:fs";
import path from "node:path";

const SRC = "assets/icons";
const OUT = "src/components/icon/icons.generated.ts";

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

const icons = {};
for (const file of fs.readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = fs.readFileSync(path.join(SRC, file), "utf8");
  icons[path.basename(file, ".svg")] = [...svg.matchAll(/<path\b[^>]*\/>/g)].map(([tag]) => {
    const p = { d: attr(tag, "d") };
    const transform = attr(tag, "transform");
    if (transform) p.transform = transform;
    // currentColor follows the <Icon color> prop; any other colour is kept
    // as-is (multi-colour brand marks like Google).
    for (const key of ["fill", "stroke"]) {
      const value = attr(tag, key);
      if (value === "currentColor") p[key] = true;
      else if (value && value !== "none") p[key] = value;
    }
    return p;
  });
}

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-icons.mjs from assets/icons. Do not edit.\n\n` +
    `export type IconPath = { d: string; transform?: string; fill?: true | string; stroke?: true | string };\n\n` +
    `export const icons = ${JSON.stringify(icons, null, 2)} satisfies Record<string, IconPath[]>;\n\n` +
    `export type IconName = keyof typeof icons;\n`,
);
console.log(`Wrote ${Object.keys(icons).length} icons to ${OUT}`);
